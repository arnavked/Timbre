import { defineConfig, type Plugin } from 'vite';

/**
 * Emit a service worker that precaches the built shell, so the whole workbench
 * runs offline after the first visit. The cache name is derived from the asset
 * list, which means a new deploy installs a fresh cache and drops the old one.
 *
 * The worker is generated at build time because hashed asset names are only
 * known then. It stays out of dev, where modules are served unbundled.
 */
function offlineShell(): Plugin {
  return {
    name: 'timbre-offline-shell',
    apply: 'build',
    generateBundle(_options, bundle) {
      // index.html is emitted by Vite's own plugin after this hook, and the
      // icons live in public/, so neither appears in `bundle`. List them by
      // hand; the shell and the manifest are what make the app installable
      // and reloadable offline.
      const extra = [
        'index.html',
        'manifest.webmanifest',
        'icon.svg',
        'icon-180.png',
        'icon-192.png',
        'icon-512.png',
        'icon-maskable-512.png',
      ];

      const files = [
        ...new Set([
          ...Object.keys(bundle).filter((name) => !name.endsWith('.map')),
          ...extra,
        ]),
      ].sort();

      let hash = 0x811c9dc5;
      for (const character of files.join('|')) {
        hash ^= character.charCodeAt(0);
        hash = Math.imul(hash, 0x01000193) >>> 0;
      }
      const version = hash.toString(36);
      const assets = files.map((name) => `./${name}`);

      const source = `/* Generated by Timbre's build. */
const CACHE = 'timbre-${version}';
const ASSETS = ${JSON.stringify(assets)};
const INDEX = new URL('./index.html', self.registration.scope).href;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) =>
        cache.addAll(ASSETS.map((path) => new URL(path, self.registration.scope).href)),
      )
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    // Network first, so a deploy is picked up; fall back to the cached shell
    // when the network fails *or* answers with an error page.
    event.respondWith(
      (async () => {
        try {
          const response = await fetch(request);
          if (response.ok) return response;
        } catch {
          // Offline or unreachable: use the cached shell below.
        }
        const cached = await caches.match(INDEX, { ignoreVary: true });
        return cached || Response.error();
      })(),
    );
    return;
  }

  // ignoreVary: static servers send "Vary: Origin", and the install-time
  // fetches don't always carry the same headers as the page's requests.
  event.respondWith(
    caches
      .match(request, { ignoreVary: true })
      .then((hit) => hit || fetch(request)),
  );
});
`;

      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

// Relative base so the build works from any path, including GitHub Pages.
export default defineConfig({
  base: './',
  plugins: [offlineShell()],
  server: {
    port: 5173,
  },
  build: {
    target: 'es2022',
    sourcemap: true,
  },
});
